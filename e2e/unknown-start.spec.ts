import { typeInput } from './input';
import { test, expect, screen } from './fixtures';
import { addPlayer, createAccount, current, newSession, openMoney, workerReady } from './helpers';

test('an offline reload leaves the start unknown until real entry and table times are corrected', async ({ page, context }, testInfo) => {
  await createAccount(page);
  await newSession(page, 'Unknown offline start');
  const player = await addPlayer(page, 'Justin');
  await workerReady(page);
  await context.setOffline(true);
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Unknown offline start', exact: true })).toBeVisible();
  await openMoney(page, player.id);
  await typeInput(page.getByLabel('Amount', { exact: true }), '100');
  await page.getByLabel('Paid now', { exact: true }).uncheck();
  await page.getByRole('button', { name: 'Save entry', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Not saved yet', exact: true })).toBeVisible();
  const stampedTime = await page.evaluate(async () => {
    const db = await new Promise<IDBDatabase>((resolve, reject) => { const request = indexedDB.open('poker-banker'); request.onsuccess = () => resolve(request.result); request.onerror = () => reject(request.error); });
    return new Promise<string | null>((resolve, reject) => { const request = db.transaction('outbox').objectStore('outbox').getAll(); request.onsuccess = () => { db.close(); resolve(request.result[0].body.occurred_at); }; request.onerror = () => reject(request.error); });
  });
  expect(stampedTime).toBeNull();
  await context.setOffline(false);
  await expect(page.getByText('Not saved yet', { exact: true })).toHaveCount(0);
  await page.reload();
  await expect(page.getByTestId('session-timer')).toHaveText('Start time unknown');
  await expect(page.getByRole('button', { name: 'Start timer', exact: true })).toHaveCount(0);
  const unknown = await current(page);
  expect(unknown.session.started_at).toBeNull();
  expect(unknown.players[0]!.duration_ms).toBeNull();
  await screen(page, testInfo, 'start-time-unknown');
  const realStart = new Date(Date.parse(unknown.server_now) - 7200000).toISOString().slice(0, 19);
  await page.getByRole('button', { name: 'Correct Buy-in $100.00', exact: true }).click();
  await typeInput(page.getByLabel('Entry time', { exact: true }), realStart);
  await page.getByRole('button', { name: 'Save correction', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  const corrected = await current(page);
  expect(corrected.session.started_at).toBeNull();
  expect(corrected.entries.find(entry => entry.kind === 'buy_in' && entry.voids_entry_id === null && entry.occurred_at !== null)?.occurred_at).toBe(`${realStart}.000Z`);
  await page.getByRole('button', { name: 'Correct times', exact: true }).click();
  await typeInput(page.getByLabel('Started at', { exact: true }), realStart);
  await page.getByRole('button', { name: 'Save timing', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  await page.reload();
  await expect(page.getByTestId('session-timer')).toContainText('Playing time');
  const saved = await current(page);
  expect(saved.session.started_at).toBe(`${realStart}.000Z`);
  expect(BigInt(saved.timing.elapsed_ms!)).toBeGreaterThanOrEqual(7200000n);
  expect(saved.events[0]!.kind).toBe('timing_corrected');
});
