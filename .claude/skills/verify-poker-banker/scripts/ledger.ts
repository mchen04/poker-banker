#!/usr/bin/env -S pnpm exec tsx
import { expect } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { RecipeContext } from './control';
import { addPlayer, newSession, openMoney, call } from '../../../../e2e/helpers';
import type { SessionState } from '../../../../src/domain/session';

export async function ledger({ page, runId, evidence, step, checkState }: RecipeContext) {
  await page.goto('/');
  await expect(page.getByRole('button', { name: 'New session', exact: true })).toBeVisible();
  const tag = `${runId.slice(-8)}-${randomUUID().slice(0, 6)}`;
  const session = await newSession(page, `Verify ledger ${tag}`);
  const player = await addPlayer(page, `Ledger Justin ${tag}`);
  const other = await addPlayer(page, `Ledger Pat ${tag}`);
  async function record(amount: string, name: string, kind: 'Buy-in' | 'Cash out' | 'Record payment' | 'Tips and meals' = 'Buy-in', paid?: boolean, method?: 'Cash' | 'Venmo' | 'Zelle') {
    await openMoney(page, player.id, kind);
    await page.getByLabel('Amount', { exact: true }).fill(amount);
    if (paid !== undefined) await page.getByLabel(kind === 'Buy-in' ? 'Paid now' : 'Paid out now', { exact: true }).setChecked(paid);
    if (method) await page.getByRole('group', { name: 'Payment method', exact: true }).getByRole('button', { name: method, exact: true }).click();
    await step(`${name}-action`);
    await page.getByRole('button', { name: 'Save entry', exact: true }).click();
    await expect(page.getByTestId('saved-confirmation')).toContainText(`$${amount}.00`);
    await expect(page.getByRole('dialog')).toHaveCount(0);
    await step(`${name}-result`);
    return checkState();
  }
  await step('bottom-buy-in-entrypoint');
  await page.getByTestId('session-bottom-bar').getByRole('button', { name: 'Buy-in', exact: true }).click();
  await page.getByLabel('Player', { exact: true }).selectOption(other.id);
  await expect(page.getByLabel('Player', { exact: true })).toHaveValue(other.id);
  await page.getByLabel('Player', { exact: true }).selectOption(player.id);
  await expect(page.getByLabel('Amount', { exact: true })).toBeEnabled();
  await page.getByLabel('Amount', { exact: true }).fill('40');
  await page.getByRole('group', { name: 'Payment method', exact: true }).getByRole('button', { name: 'Venmo', exact: true }).click();
  await step('bottom-buy-in-40-venmo-action');
  await page.getByRole('button', { name: 'Save entry', exact: true }).click();
  await expect(page.getByTestId('saved-confirmation')).toContainText('$40.00');
  await expect(page.getByTestId('activity')).toContainText('Venmo');
  await step('bottom-buy-in-confirmed');
  await record('20', 'player-sheet-rebuy', 'Buy-in', false);
  await expect(page.getByTestId(`player-${player.id}`)).toContainText('Owes $20.00');
  await step('player-sheet-rebuy-unpaid-result');
  await record('20', 'payment-zelle', 'Record payment', undefined, 'Zelle');
  await step('payment-zelle-confirmed');
  await record('70', 'early-cash-out', 'Cash out');
  await expect(page.getByTestId(`result-${player.id}`)).toContainText('+$10.00');
  await step('early-cash-out-result');
  await record('10', 're-entry', 'Buy-in', false);
  await expect(page.getByTestId(`result-${player.id}`)).toContainText('Playing');
  await expect(page.getByTestId(`result-${player.id}`)).not.toContainText('+$10.00');
  await step('re-entry-result-hidden');
  let state = await record('5', 'final-cash-out', 'Cash out');
  const original = state.entries.find(row => row.kind === 'cash_out' && row.amount_minor === '500')!;
  await page.getByTestId(`entry-${original.id}`).getByRole('button').click();
  await page.getByLabel('Replacement amount', { exact: true }).fill('6');
  await step('workspace-correction-action');
  await page.getByRole('button', { name: 'Save correction', exact: true }).click();
  await expect(page.getByTestId(`entry-${original.id}`)).toContainText('Voided');
  await expect(page.getByTestId(`entry-${original.id}`).locator('.voided')).toHaveCSS('text-decoration-line', 'line-through');
  await expect(page.getByTestId(`result-${player.id}`)).toContainText('+$6.00');
  await step('workspace-correction-result');
  state = await record('2', 'tips-and-meals', 'Tips and meals');
  const expense = state.entries.find(row => row.kind === 'expense')!;
  await page.getByTestId(`player-${player.id}`).click();
  await page.getByRole('dialog').getByTestId(`entry-${expense.id}`).getByRole('button').click();
  await step('player-entries-void-action');
  await page.getByRole('button', { name: 'Void entry', exact: true }).click();
  await expect(page.getByTestId(`entry-${expense.id}`)).toContainText('Voided');
  await step('player-entries-void-result');
  state = await checkState();
  const payment = state.entries.find(row => row.kind === 'payment_in' && row.method === 'zelle')!;
  await page.getByTestId(`entry-${payment.id}`).getByRole('button').click();
  await page.getByRole('group', { name: 'Replacement method', exact: true }).getByRole('button', { name: 'Cash', exact: true }).click();
  await step('payment-method-correction-action');
  await page.getByRole('button', { name: 'Save correction', exact: true }).click();
  await expect(page.getByTestId(`entry-${payment.id}`)).toContainText('Voided');
  state = await checkState();
  expect(state.entries).toHaveLength(13);
  expect(state.entries.filter(row => row.voids_entry_id)).toHaveLength(3);
  expect(state.players.find(row => row.id === player.id)).toMatchObject({ state: 'cashed_out', result_minor: '600', balance_minor: '-6600', bought_in_minor: '7000', cashed_out_minor: '7600' });
  expect(state.totals.total_in_minor).toBe('7000');
  expect(state.totals.total_out_minor).toBe('7600');
  expect(state.entries.find(row => row.kind === 'payment_in' && row.method === 'cash' && !row.voids_entry_id)?.amount_minor).toBe('2000');
  const reread = await call<SessionState>(page, `/sessions/${session.session.id}`);
  expect(reread.revision).toBe(state.revision);
  await writeFile(join(evidence, 'ledger-state.json'), JSON.stringify(reread, null, 2));
  await step('corrected-ledger-read-only-api-proof');
  await page.reload();
  await expect(page.getByTestId(`result-${player.id}`)).toContainText('+$6.00');
  await expect(page.getByTestId(`entry-${payment.id}`)).toContainText('Zelle');
  await expect(page.getByTestId('activity')).toContainText('Cash');
  await step('reload-preserves-corrections');
  await openMoney(page, player.id);
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
}
