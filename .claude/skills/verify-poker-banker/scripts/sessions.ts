import { typeInput } from '../../../../e2e/input';
import { randomUUID } from 'node:crypto';
import { expect } from '@playwright/test';
import { addPlayer, call, current, keepMoneyDraft, menu, openMoney, openNewSession, storedDraft, switchSession, workspaceReady } from '../../../../e2e/helpers';
import type { RecipeContext } from './control';
import type { SessionState } from '../../../../src/domain/session';

export default async function ({ page, banker, runId, step, checkState }: RecipeContext) {
  await page.goto('/');
  await workspaceReady(page);
  const tag = `${runId.slice(-8)}-${randomUUID().slice(0, 6)}`;
  const name = `Verify ${tag}`;
  const firstName = `${name} early`;
  const secondName = `${name} late`;
  const welcome = page.getByRole('button', { name: 'Create your first session', exact: true });
  const existing = await call<{ sessions: { id: string }[] }>(page, '/sessions');
  const empty = existing.sessions.length === 0;
  if (empty) await expect(welcome).toBeVisible();
  else {
    await expect(page.getByRole('button', { name: 'Switch session', exact: true })).toHaveAttribute('data-testid', /^session-tab-/);
    await expect(welcome).toHaveCount(0);
  }
  await step(empty ? 'sessions-welcome-create-before' : 'sessions-header-create-before');
  await openNewSession(page);
  await typeInput(page.getByLabel('Session name', { exact: true }), firstName);
  await typeInput(page.getByLabel('Session date', { exact: true }), '2026-11-10');
  await typeInput(page.getByLabel('Location', { exact: true }), 'Verify Home');
  await typeInput(page.getByLabel('Game', { exact: true }), 'NLH');
  await typeInput(page.getByLabel('Big blind', { exact: true }), '2');
  await page.getByRole('button', { name: 'Create session', exact: true }).click();
  await expect(page.getByRole('heading', { name: firstName, exact: true })).toBeVisible();
  const first = await current(page);
  const player = await addPlayer(page, name);
  await openMoney(page, player.id);
  await typeInput(page.getByTestId('money-amount'), '12.');
  await keepMoneyDraft(page);
  await page.getByRole('button', { name: 'Switch session', exact: true }).click();
  await page.getByRole('dialog', { name: 'Sessions', exact: true }).getByRole('button', { name: 'New session', exact: true }).click();
  await typeInput(page.getByLabel('Session name', { exact: true }), secondName);
  await page.getByRole('button', { name: 'Create session', exact: true }).click();
  await expect(page.getByRole('heading', { name: secondName, exact: true })).toBeVisible();
  const second = await current(page);
  await menu(page, 'Session settings');
  await expect(page.locator('#past-locations option').filter({ hasText: 'Verify Home' })).toHaveCount(1);
  await expect(page.locator('#past-games option').filter({ hasText: 'NLH' })).toHaveCount(1);
  await typeInput(page.getByLabel('Location', { exact: true }), 'Verify Home');
  await typeInput(page.getByLabel('Game', { exact: true }), 'NLH');
  await typeInput(page.getByLabel('Big blind', { exact: true }), '1');
  await page.getByRole('button', { name: 'Save settings', exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  expect((await checkState()).session.big_blind_minor).toBe('100');
  await page.getByRole('button', { name: 'Add player', exact: true }).click();
  await typeInput(page.getByLabel('Search players', { exact: true }), name);
  await expect(page.getByLabel('Search players', { exact: true })).toHaveValue(name);
  await expect(page.getByText('An exact name match already exists.', { exact: false })).toBeVisible();
  await expect(page.getByRole('button', { name: `Add '${name}' as new`, exact: true })).toBeDisabled();
  await step('sessions-existing-player-warning');
  await page.getByRole('dialog').getByRole('button', { name, exact: true }).click();
  await openMoney(page, player.id);
  await typeInput(page.getByTestId('money-amount'), '34.');
  await expect.poll(async () => (await storedDraft<{ amount: string }>(page, `${banker.id}/${second.session.id}/buy_in/${player.id}`))?.amount).toBe('34.');
  await page.reload();
  await openMoney(page, player.id);
  await expect(page.getByTestId('money-amount')).toHaveValue('34.');
  await step('sessions-late-draft-restored');
  await keepMoneyDraft(page);
  await switchSession(page, first.session.id);
  await openMoney(page, player.id);
  await expect(page.getByTestId('money-amount')).toHaveValue('12.');
  await step('sessions-early-draft-restored');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Keep editing', exact: true }).click();
  await expect(page.getByTestId('money-amount')).toHaveValue('12.');
  await keepMoneyDraft(page);
  for (let index = 0; index < 31; index++) {
    const older = await call<SessionState>(page, '/sessions', 'POST', { op_id: randomUUID(), name: `${name} older ${index}`, played_on: `2025-${String(1 + index % 12).padStart(2, '0')}-01`, currency: 'USD' });
    await call(page, `/sessions/${older.session.id}/close`, 'POST', { op_id: randomUUID(), expected_revision: older.revision });
  }
  const oldOpen = await call<SessionState>(page, '/sessions', 'POST', { op_id: randomUUID(), name: `${name} unfinished`, played_on: '2024-01-01', currency: 'USD' });
  await page.getByRole('button', { name: 'Switch session', exact: true }).click();
  const matchingHistory = page.waitForResponse(response => {
    const url = new URL(response.url());
    return response.request().method() === 'GET' && url.pathname === '/api/sessions' && url.searchParams.get('q') === name && !url.searchParams.has('before');
  });
  await typeInput(page.getByLabel('Search sessions', { exact: true }), name);
  const firstHistoryPage = await matchingHistory;
  expect(firstHistoryPage.status()).toBe(200);
  expect((await firstHistoryPage.json()).sessions.some((session: { id: string }) => session.id === oldOpen.session.id)).toBe(false);
  await expect(page.getByRole('region', { name: 'Current and open sessions', exact: true }).getByTestId(`session-tab-${oldOpen.session.id}`)).toBeVisible();
  await expect(page.getByRole('dialog').getByRole('button', { name: new RegExp(name) })).toHaveCount(31);
  await expect(page.getByRole('heading', { name: 'November 2025', exact: true })).toBeVisible();
  await expect(page.getByRole('button', { name: 'Load more sessions', exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Load more sessions', exact: true }).click();
  await expect(page.getByRole('button', { name: 'Load more sessions', exact: true })).toHaveCount(0);
  await step('sessions-closed-history-month-pagination');
  const lateHistory = page.waitForResponse(response => {
    const url = new URL(response.url());
    return response.request().method() === 'GET' && url.pathname === '/api/sessions' && url.searchParams.get('q') === secondName;
  });
  await typeInput(page.getByLabel('Search sessions', { exact: true }), secondName);
  expect((await lateHistory).status()).toBe(200);
  await expect(page.getByRole('dialog').getByRole('button', { name: new RegExp(name) })).toHaveCount(1);
  await expect(page.getByRole('heading', { name: 'Current and open sessions', exact: true })).toBeVisible();
  await step('sessions-pinned-open-search');
  await page.getByRole('dialog').getByRole('button', { name: new RegExp(secondName) }).click();
  await expect(page.getByRole('heading', { name: secondName, exact: true })).toBeVisible();
  expect(new URL(page.url()).searchParams.get('session')).toBe(second.session.id);
  await openMoney(page, player.id);
  await expect(page.getByTestId('money-amount')).toHaveValue('34.');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Discard draft', exact: true }).click();
  await openMoney(page, player.id);
  await expect(page.getByTestId('money-amount')).toHaveValue('');
  await page.getByRole('button', { name: 'Cancel', exact: true }).click();
  await page.getByRole('button', { name: 'Add player', exact: true }).click();
  await typeInput(page.getByLabel('Search players', { exact: true }), name);
  await expect(page.getByText('An exact name match already exists.', { exact: false })).toBeVisible();
  await page.getByLabel('This is a different person', { exact: true }).check();
  await page.getByRole('button', { name: `Add '${name}' as new`, exact: true }).click();
  await expect(page.getByRole('dialog')).toHaveCount(0);
  expect((await checkState()).players.filter(player => player.display_name === name)).toHaveLength(2);
  await step('sessions-distinct-person-confirmed');
}
