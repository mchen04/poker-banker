import { expect, type Page } from '@playwright/test';
import { writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import type { RecipeContext } from './control';
import { addPlayer, call, current, menu, money, newContextLike, newSession, share, workerReady, workspaceReady } from '../../../../e2e/helpers';

const row = (page: Page, id: string) => page.locator('.session-board').getByTestId('activity').getByTestId(`entry-${id}`);
const toast = (page: Page) => page.getByTestId('save-status');
const nav = (page: Page, name: 'Table' | 'Players') => page.getByRole('navigation', { name: 'Table navigation', exact: true }).getByRole('button', { name, exact: true }).click();

export default async function deletions({ page, context, browser, baseURL, runId, evidence, step }: RecipeContext) {
  const tag = runId.slice(-6);
  const proof: Record<string, unknown> = {};
  await page.goto('/');
  await workspaceReady(page);
  await workerReady(page);
  const older = await newSession(page, `Deletion older ${tag}`);
  const sessionName = `Deletion game ${tag}`;
  await newSession(page, sessionName);
  const sam = await addPlayer(page, `Sam ${tag}`);
  const longName = `Alexandria Montgomery-Whitfield ${tag}`;
  const alexandria = await addPlayer(page, longName);
  await money(page, sam.id, '50', { paid: false });
  await money(page, alexandria.id, '123456789', { paid: false });
  let state = await money(page, alexandria.id, '25', { paid: false });
  expect(state.totals.total_in_minor).toBe('12345686400');
  const samBuy = state.entries.find(entry => entry.player_id === sam.id && entry.kind === 'buy_in')!;
  await step('setup-two-players');

  await row(page, samBuy.id).getByRole('button').click();
  await page.getByRole('button', { name: 'Delete entry', exact: true }).click();
  await expect(page.getByRole('alertdialog', { name: 'Delete entry', exact: true })).toContainText(`Delete Sam ${tag}'s $50.00 buy-in?`);
  expect((await current(page)).revision).toBe(state.revision);
  await step('delete-entry-confirm');
  await page.getByRole('button', { name: 'Confirm delete', exact: true }).click();
  await expect(toast(page)).toContainText(`Deleted buy-in · Sam ${tag} · $50.00`);
  await expect(row(page, samBuy.id)).toContainText('Deleted');
  state = await current(page);
  expect(state.totals.total_in_minor).toBe('12345681400');
  await step('delete-entry-toast');
  await toast(page).getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(toast(page)).toContainText(`Restored buy-in · Sam ${tag} · $50.00`);
  state = await current(page);
  expect(state.totals.total_in_minor).toBe('12345686400');
  const copy = state.entries.find(entry => entry.restores_entry_id === samBuy.id)!;
  await step('delete-entry-undo');
  await row(page, copy.id).getByRole('button').click();
  await page.getByRole('button', { name: 'Delete entry', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm delete', exact: true }).click();
  await expect(toast(page)).toContainText(`Deleted buy-in · Sam ${tag} · $50.00`);
  await page.waitForTimeout(9000);
  await row(page, copy.id).getByRole('button', { name: /^Deleted Buy-in \$50\.00 · / }).click();
  await step('restore-entry-sheet');
  await page.getByRole('button', { name: 'Restore entry', exact: true }).click();
  await expect(toast(page)).toContainText(`Restored buy-in · Sam ${tag} · $50.00`);
  state = await current(page);
  expect(state.totals.total_in_minor).toBe('12345686400');
  proof.entry = { deleted: samBuy.id, restoredCopy: copy.id, totalAfterRestore: state.totals.total_in_minor };
  await step('restore-entry-later');

  const samCopy = state.entries.find(entry => entry.restores_entry_id === copy.id)!;
  await context.setOffline(true);
  try {
    await row(page, samCopy.id).getByRole('button').click();
    await page.getByRole('button', { name: 'Delete entry', exact: true }).click();
    await page.getByRole('button', { name: 'Confirm delete', exact: true }).click();
    await expect(page.getByLabel('Unsent entries', { exact: true })).toContainText(`Delete buy-in · Sam ${tag} · $50.00`);
    await expect(row(page, samCopy.id)).toContainText('Delete pending');
    await expect(page.getByTestId(`player-${sam.id}`)).toContainText('$50.00');
    await step('offline-delete-pending-totals-unchanged');
    await page.reload();
    await expect(page.getByLabel('Unsent entries', { exact: true })).toContainText(`Delete buy-in · Sam ${tag} · $50.00`);
    await step('offline-delete-survives-reload');
  } finally { await context.setOffline(false); }
  await expect(toast(page)).toContainText(`Deleted buy-in · Sam ${tag} · $50.00`);
  await expect(page.getByLabel('Unsent entries', { exact: true })).toHaveCount(0);
  state = await current(page);
  expect(state.totals.total_in_minor).toBe('12345681400');
  expect(state.entries.filter(entry => entry.voids_entry_id === samCopy.id)).toHaveLength(1);
  proof.offline = { deleted: samCopy.id, totalAfterSync: state.totals.total_in_minor };
  await step('offline-delete-synced-once');

  await page.getByTestId(`player-${alexandria.id}`).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Remove from game', exact: true }).click();
  await expect(page.getByRole('alertdialog', { name: 'Remove player', exact: true })).toContainText('Their 2 entries will be deleted. Totals update right away.');
  await step('remove-player-confirm');
  await page.getByRole('button', { name: 'Confirm remove', exact: true }).click();
  await expect(toast(page)).toContainText(`Removed ${longName}`);
  state = await current(page);
  expect(state.removed_players.map(player => player.id)).toEqual([alexandria.id]);
  expect(state.totals.total_in_minor).toBe('0');
  await step('remove-player-toast');
  await toast(page).getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.getByTestId(`player-${alexandria.id}`)).toBeVisible();
  expect((await current(page)).totals.total_in_minor).toBe('12345681400');
  await step('remove-player-undo');
  await page.getByTestId(`player-${alexandria.id}`).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Remove from game', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm remove', exact: true }).click();
  await expect(toast(page)).toContainText(`Removed ${longName}`);
  await page.waitForTimeout(9000);
  await page.getByTestId('removed-players').getByText('Removed (1)', { exact: true }).click();
  await step('removed-disclosure');
  await page.getByTestId('removed-players').getByRole('button', { name: `Restore ${longName}`, exact: true }).click();
  await expect(page.getByTestId(`player-${alexandria.id}`)).toBeVisible();
  state = await current(page);
  expect(state.totals.total_in_minor).toBe('12345681400');
  proof.removal = { player: alexandria.id, totalAfterRestore: state.totals.total_in_minor };
  await step('removed-player-restored');

  const link = await share(page);
  const before = state.totals.total_in_minor;
  await menu(page, 'Delete session');
  await expect(page.getByRole('alertdialog', { name: 'Delete session', exact: true })).toContainText(`Delete ${sessionName}?`);
  await step('delete-session-confirm');
  await page.getByRole('button', { name: 'Confirm delete', exact: true }).click();
  await expect(toast(page)).toContainText(`Deleted ${sessionName}`);
  await expect(page.getByRole('heading', { name: sessionName, exact: true })).toHaveCount(0);
  expect((await call<{ sessions: { id: string }[] }>(page, '/sessions/deleted')).sessions.map(item => item.id)).toContain(state.session.id);
  await step('delete-session-toast');
  const viewerContext = await newContextLike(page, browser, baseURL);
  try {
    const viewer = await viewerContext.newPage();
    await viewer.goto(link);
    await expect(viewer.getByRole('heading', { name: "This viewer link isn’t available" })).toBeVisible();
    await expect(viewer.getByText('Ask the banker for a current link.', { exact: true })).toBeVisible();
    await viewer.screenshot({ path: join(evidence, 'deleted-session-viewer.png') });
  } finally { await viewerContext.close(); }
  await toast(page).getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.getByRole('heading', { name: sessionName, exact: true })).toBeVisible();
  expect((await current(page)).totals.total_in_minor).toBe(before);
  await step('delete-session-undo');
  await menu(page, 'Delete session');
  await page.getByRole('button', { name: 'Confirm delete', exact: true }).click();
  await expect(toast(page)).toContainText(`Deleted ${sessionName}`);
  await page.waitForTimeout(9000);
  await page.getByRole('button', { name: 'Switch session', exact: true }).click();
  const picker = page.getByRole('dialog', { name: 'Sessions', exact: true });
  await picker.getByText(/^Recently deleted \(\d+\)$/).click();
  await step('recently-deleted-sessions');
  await picker.getByRole('button', { name: `Restore ${sessionName}`, exact: true }).click();
  await expect(page.getByRole('heading', { name: sessionName, exact: true })).toBeVisible();
  state = await current(page);
  expect(state.totals.total_in_minor).toBe(before);
  proof.session = { id: state.session.id, other: older.session.id, totalAfterRestore: state.totals.total_in_minor };
  await step('session-restored');

  const jordan = await addPlayer(page, `Jordan ${tag}`);
  await nav(page, 'Players');
  await page.getByTestId(`roster-player-${jordan.id}`).click();
  await page.getByRole('button', { name: 'Delete player', exact: true }).click();
  await expect(page.getByRole('dialog', { name: 'Delete player', exact: true })).toContainText('Remove them from their games first');
  await step('delete-seated-player-refused');
  await page.getByRole('button', { name: 'Close sheet', exact: true }).click();
  await nav(page, 'Table');
  await page.getByTestId(`player-${jordan.id}`).click();
  await page.getByRole('dialog').getByRole('button', { name: 'Remove from game', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm remove', exact: true }).click();
  await expect(toast(page)).toContainText(`Removed Jordan ${tag}`);
  await nav(page, 'Players');
  await page.getByTestId(`roster-player-${jordan.id}`).click();
  await page.getByRole('button', { name: 'Delete player', exact: true }).click();
  await step('delete-player-confirm');
  await page.getByRole('button', { name: 'Confirm delete', exact: true }).click();
  await expect(toast(page)).toContainText(`Deleted Jordan ${tag}`);
  expect((await call<{ players: { id: string }[] }>(page, '/players')).players.map(item => item.id)).not.toContain(jordan.id);
  await step('delete-player-toast');
  await toast(page).getByRole('button', { name: 'Undo', exact: true }).click();
  await expect(page.getByTestId(`roster-player-${jordan.id}`)).toBeVisible();
  await page.getByTestId(`roster-player-${jordan.id}`).click();
  await page.getByRole('button', { name: 'Delete player', exact: true }).click();
  await page.getByRole('button', { name: 'Confirm delete', exact: true }).click();
  await expect(toast(page)).toContainText(`Deleted Jordan ${tag}`);
  await page.getByTestId('recently-deleted-players').getByText(/^Recently deleted \(\d+\)$/).click();
  await step('recently-deleted-players');
  await page.getByTestId('recently-deleted-players').getByRole('button', { name: `Restore Jordan ${tag}`, exact: true }).click();
  await expect(page.getByTestId(`roster-player-${jordan.id}`)).toBeVisible();
  expect((await call<{ players: { id: string }[] }>(page, '/players')).players.map(item => item.id)).toContain(jordan.id);
  proof.player = { id: jordan.id, restored: true };
  await step('roster-player-restored');
  await nav(page, 'Table');
  await writeFile(join(evidence, 'deletions-proof.json'), JSON.stringify(proof, null, 2));
}
